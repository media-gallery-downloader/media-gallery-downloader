<?php

use App\Services\Sites\SiteCookieCopy;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Illuminate\Support\Facades\File;

uses(RefreshDatabase::class);

function cookieLine(string $value): string
{
    return ".reddit.com\tTRUE\t/\tTRUE\t9999999999\treddit_session\t{$value}";
}

beforeEach(function () {
    $this->cookiesDir = useTemporaryCookiesDirectory();
    $this->runDir = storage_path('framework/testing/run_'.str_replace('.', '', uniqid('', true)));
    File::ensureDirectoryExists($this->runDir);

    $this->site = makeSite('Reddit', ['reddit.com']);
    $this->site->storeCookies(cookieLine('ORIGINAL')."\n");
});

afterEach(function () {
    File::deleteDirectory($this->cookiesDir);
    File::deleteDirectory($this->runDir);
});

/** What yt-dlp does at the end of a run: rewrite its cookie file in place. */
function ytDlpRewrites(SiteCookieCopy $copy, string $value): void
{
    file_put_contents($copy->path, "# Netscape HTTP Cookie File\n# This file is generated by yt-dlp.  Do not edit.\n\n".cookieLine($value)."\n");
}

it('gives a yt-dlp run its own private copy of the site\'s cookies', function () {
    $copy = SiteCookieCopy::create($this->site, $this->runDir);

    clearstatcache();
    expect($copy->path)->not->toBe($this->site->cookiesPath())
        ->and(dirname($copy->path))->toBe($this->runDir)
        ->and(basename($copy->path))->toStartWith('.')
        ->and(file_get_contents($copy->path))->toBe(file_get_contents($this->site->cookiesPath()))
        ->and(fileperms($copy->path) & 0777)->toBe(0600);
});

it('has no copy for a site without cookies', function () {
    expect(SiteCookieCopy::create(makeSite('YouTube', ['youtube.com']), $this->runDir))->toBeNull();
});

it('keeps the cookies yt-dlp refreshed', function () {
    $copy = SiteCookieCopy::create($this->site, $this->runDir);
    ytDlpRewrites($copy, 'REFRESHED');

    $copy->writeBack();

    expect(file_get_contents($this->site->cookiesPath()))->toBe("# Netscape HTTP Cookie File\n".cookieLine('REFRESHED')."\n");
});

it('never undoes cookies pasted while the run was going', function () {
    $copy = SiteCookieCopy::create($this->site, $this->runDir);
    $this->site->storeCookies(cookieLine('PASTED')."\n");
    ytDlpRewrites($copy, 'REFRESHED');

    $copy->writeBack();

    expect(file_get_contents($this->site->cookiesPath()))->toContain('PASTED')->not->toContain('REFRESHED');
});

it('never brings back cookies cleared while the run was going', function () {
    $copy = SiteCookieCopy::create($this->site, $this->runDir);
    $this->site->clearCookies();
    ytDlpRewrites($copy, 'REFRESHED');

    $copy->writeBack();

    expect($this->site->hasCookies())->toBeFalse();
});

it('leaves nothing behind for a site deleted while the run was going', function () {
    $copy = SiteCookieCopy::create($this->site, $this->runDir);
    $livePath = $this->site->cookiesPath();
    $this->site->delete();
    ytDlpRewrites($copy, 'REFRESHED');

    $copy->writeBack();

    expect(file_exists($livePath))->toBeFalse()
        ->and(file_exists($copy->path))->toBeFalse();
});

it('removes the private copy once the run is over', function () {
    $copy = SiteCookieCopy::create($this->site, $this->runDir);

    $copy->writeBack();

    expect(file_exists($copy->path))->toBeFalse();
});

it('replaces a site\'s cookie file without leaving temporary files', function () {
    $this->site->storeCookies(cookieLine('PASTED')."\n");

    $files = array_map('basename', glob($this->cookiesDir.'/*') ?: []);
    expect($files)->toBe([basename($this->site->cookiesPath())]);
});
